// ส่วนที่ 1 — ฟังก์ชันตรวจสอบสิทธิ์ตามลำดับที่กำหนด
function login(inputUser, inputPass, role, isActive, age) {
  // ข้อมูลที่ถูกต้องในระบบ
  const VALID_USER = "admin";
  const VALID_PASS = "ce385pass";

  // ลำดับที่ 1: ตรวจสอบ username หรือ password (ใช้ ||)
  if (inputUser !== VALID_USER || inputPass !== VALID_PASS) {
    return "ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง";
  }

  // ลำดับที่ 2: ตรวจสอบบัญชีถูกระงับ (isActive เป็น false)
  if (!isActive) {
    return "บัญชีนี้ถูกระงับการใช้งาน";
  }

  // ลำดับที่ 3: ตรวจสอบอายุน้อยกว่า 18
  if (age < 18) {
    return "อายุไม่ถึงเกณฑ์";
  }

  // ลำดับที่ 4 & 5: ผ่านทุกข้อ และตรวจสอบสิทธิ์ (ใช้ &&)
  if (role === "อาจารย์") {
    return "เข้าสู่ระบบสำเร็จ (สิทธิ์ผู้ดูแล)";
  } else if (role === "นักศึกษา") {
    return "เข้าสู่ระบบสำเร็จ (สิทธิ์ทั่วไป)";
  }

  return "สิทธิ์ใช้งานไม่ถูกต้อง";
}

// ส่วนที่ 2 — ทดสอบอย่างน้อย 6 กรณี
const testCases = [
  { user: "admin", pass: "ce385pass", role: "อาจารย์", active: true, age: 30, desc: "กรณี 1: สำเร็จ (อาจารย์)" },
  { user: "admin", pass: "ce385pass", role: "นักศึกษา", active: true, age: 20, desc: "กรณี 2: สำเร็จ (นักศึกษา)" },
  { user: "admin", pass: "wrong123", role: "นักศึกษา", active: true, age: 20, desc: "กรณี 3: รหัสผ่านผิด" },
  { user: "wrongUser", pass: "ce385pass", role: "อาจารย์", active: true, age: 35, desc: "กรณี 4: ชื่อผู้ใช้ผิด" },
  { user: "admin", pass: "ce385pass", role: "นักศึกษา", active: false, age: 22, desc: "กรณี 5: บัญชีถูกระงับ" },
  { user: "admin", pass: "ce385pass", role: "นักศึกษา", active: true, age: 16, desc: "กรณี 6: อายุไม่ถึง" }
];

console.log("===== ผลการทดสอบระบบตรวจสอบสิทธิ์ =====");
for (const test of testCases) {
  const result = login(test.user, test.pass, test.role, test.active, test.age);
  console.log(`[${test.desc}] -> ${result}`);
}
